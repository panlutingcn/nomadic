export function calcPersona(answers: Record<number, 'A' | 'B'>): string {
  const axes = [
    { qs: [0, 1, 2, 3], A: 'S', B: 'D' },
    { qs: [4, 5, 6, 7], A: 'C', B: 'V' },
    { qs: [8, 9, 10, 11], A: 'L', B: 'T' },
    { qs: [12, 13, 14, 15], A: 'P', B: 'F' },
  ]
  return axes.map(({ qs, A, B }) => {
    const aCount = qs.filter(q => answers[q] === 'A').length
    return aCount >= 2 ? A : B
  }).join('')
}

